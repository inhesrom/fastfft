//! Emits Rust source for codelet graphs.

use crate::dag::{Graph, Op};
use crate::dft::Kind;
use std::fmt::Write;

fn fmt_const(c: f64) -> String {
    let s = format!("{c:?}");
    if s.contains('.') || s.contains('e') {
        s
    } else {
        format!("{s}.0")
    }
}

/// Emits one codelet function.
pub fn emit_fn(g: &Graph, r: usize, kind: Kind) -> String {
    emit_variant(g, r, kind, false)
}

fn emit_variant(g: &Graph, r: usize, kind: Kind, latency: bool) -> String {
    let mut name = match kind {
        Kind::Notw => format!("n{r}"),
        Kind::Tw => format!("t{r}"),
    };
    if latency {
        assert!(!g.dag.nodes.iter().any(|o| matches!(o, Op::One)));
        name.insert(0, 's');
    }
    let c = g.counts();
    let mut s = String::new();
    let _ = writeln!(
        s,
        "/// Forward DFT-{r}{}. Ops: {} add/sub, {} mul, {} fma, {} neg (add pipe {}, fma pipe {}).",
        if kind == Kind::Tw {
            " with DIT input twiddles `x[j] *= w[j]` for `j >= 1`"
        } else {
            ""
        },
        c.add,
        c.mul,
        c.fma,
        c.neg,
        c.add_pipe(),
        c.fma_pipe()
    );
    let _ = writeln!(s, "#[inline(always)]");
    let one_arg = if latency { "" } else { ", one: V" };
    let args = match kind {
        Kind::Notw => format!("re: &mut [V; {r}], im: &mut [V; {r}]{one_arg}"),
        Kind::Tw => {
            format!("re: &mut [V; {r}], im: &mut [V; {r}], wr: &[V; {r}], wi: &[V; {r}]{one_arg}")
        }
    };
    let _ = writeln!(s, "pub(crate) unsafe fn {name}<V: SimdReal>({args}) {{");
    let _ = writeln!(
        s,
        "// SAFETY: register arithmetic only; callers run inside a `#[target_feature]` context for `V`."
    );
    let _ = writeln!(s, "unsafe {{");
    let uses_one = g.dag.nodes.iter().any(|o| matches!(o, Op::One));
    if !uses_one && !latency {
        let _ = writeln!(s, "let _ = one;");
    }
    let name_of = |i: usize| -> String {
        match g.dag.nodes[i] {
            Op::Input(k) => format!("x{k}"),
            Op::Tw(k) => format!("w{k}"),
            Op::One => "one".to_string(),
            Op::Const(_) => format!("k{i}"),
            _ => format!("t{i}"),
        }
    };
    // inputs, twiddles and constants first
    for (i, op) in g.dag.nodes.iter().enumerate() {
        match *op {
            Op::Input(k) => {
                let arr = if k % 2 == 0 { "re" } else { "im" };
                let _ = writeln!(s, "let x{k} = {arr}[{}];", k / 2);
            }
            Op::Tw(k) => {
                let arr = if k % 2 == 0 { "wr" } else { "wi" };
                let _ = writeln!(s, "let w{k} = {arr}[{}];", k / 2 + 1);
            }
            Op::Const(c) => {
                let _ = writeln!(s, "let k{i} = V::splat_f64({});", fmt_const(c));
            }
            _ => {}
        }
    }
    for (i, op) in g.dag.nodes.iter().enumerate() {
        let n = |x: usize| name_of(x);
        let e = match *op {
            Op::Add(a, b) => format!("V::add({}, {})", n(a), n(b)),
            Op::Sub(a, b) => format!("V::sub({}, {})", n(a), n(b)),
            Op::Neg(a) => format!("V::neg({})", n(a)),
            Op::Mul(a, b) => format!("V::mul({}, {})", n(a), n(b)),
            Op::MulAdd(a, b, c) => format!("V::fmadd({}, {}, {})", n(a), n(b), n(c)),
            Op::MulSub(a, b, c) => format!("V::fmsub({}, {}, {})", n(a), n(b), n(c)),
            Op::NegMulAdd(a, b, c) => format!("V::fnmadd({}, {}, {})", n(a), n(b), n(c)),
            _ => continue,
        };
        let _ = writeln!(s, "let t{i} = {e};");
    }
    for (k, &o) in g.outputs.iter().enumerate() {
        let arr = if k % 2 == 0 { "re" } else { "im" };
        let _ = writeln!(s, "{arr}[{}] = {};", k / 2, name_of(o));
    }
    let _ = writeln!(s, "}}\n}}\n");
    s
}

pub const HEADER: &str =
    "// @generated by fastfft-codegen (`cargo xtask codegen`). Do not edit by hand.\n";

/// One file per radix: `n{r}` and `t{r}`.
pub fn emit_radix_file(r: usize, n: &Graph, t: &Graph) -> String {
    let sn = crate::dft::build(r, Kind::Notw, false);
    let st = crate::dft::build(r, Kind::Tw, false);
    emit_radix_file_with_latency(r, n, t, &sn, &st)
}

pub(crate) fn emit_radix_file_with_latency(
    r: usize,
    n: &Graph,
    t: &Graph,
    sn: &Graph,
    st: &Graph,
) -> String {
    let mut s = String::new();
    s.push_str(HEADER);
    let _ = writeln!(s, "//! Size-{r} codelets.\n");
    s.push_str("#![allow(clippy::all, clippy::pedantic, unused_variables, non_snake_case)]\n\n");
    s.push_str("use crate::isa::SimdReal;\n\n");
    s.push_str(&emit_fn(n, r, Kind::Notw));
    s.push_str(&emit_fn(t, r, Kind::Tw));
    s.push_str("// Latency-oriented variants: FMA fusion, without add-pipe balancing.\n");
    s.push_str(&emit_variant(sn, r, Kind::Notw, true));
    s.push_str(&emit_variant(st, r, Kind::Tw, true));
    s
}

/// `mod.rs` with dispatch helpers and op-count tables.
pub fn emit_mod(radices: &[usize], counts: &[(usize, [usize; 2], [usize; 2])]) -> String {
    let mut s = String::new();
    s.push_str(HEADER);
    s.push_str("//! Generated straight-line DFT codelets (split re/im layout).\n\n");
    s.push_str("#![allow(clippy::all, dead_code)]\n\n");
    for r in radices {
        let _ = writeln!(s, "pub(crate) mod r{r};");
    }
    s.push_str("\nuse crate::isa::SimdReal;\n\n");
    let list: Vec<String> = radices.iter().map(|r| r.to_string()).collect();
    let _ = writeln!(
        s,
        "/// Radices with generated codelets.\npub(crate) const RADICES: &[usize] = &[{}];\n",
        list.join(", ")
    );
    s.push_str("/// (radix, [notw add-pipe ops, notw fma-pipe ops], [tw add-pipe ops, tw fma-pipe ops]).\n");
    s.push_str("pub(crate) const OP_COUNTS: &[(usize, [usize; 2], [usize; 2])] = &[\n");
    for (r, n, t) in counts {
        let _ = writeln!(s, "    ({r}, [{}, {}], [{}, {}]),", n[0], n[1], t[0], t[1]);
    }
    s.push_str("];\n\n");
    // dispatch
    s.push_str("/// Forward DFT-`R` without twiddles (`R` must be in [`RADICES`]).\n");
    s.push_str("#[inline(always)]\npub(crate) unsafe fn notw<V: SimdReal, const R: usize>(re: &mut [V; R], im: &mut [V; R], one: V) {\n");
    s.push_str("    // SAFETY: each arm only runs when R equals the array length it casts to.\n    unsafe {\n        match R {\n");
    for r in radices {
        let _ = writeln!(
            s,
            "            {r} => r{r}::n{r}(&mut *(re as *mut [V; R]).cast::<[V; {r}]>(), &mut *(im as *mut [V; R]).cast::<[V; {r}]>(), one),"
        );
    }
    s.push_str("            _ => unreachable!(),\n        }\n    }\n}\n\n");
    s.push_str("/// Forward DFT-`R` with DIT input twiddles (`w[0]` unused).\n");
    s.push_str("#[inline(always)]\npub(crate) unsafe fn tw<V: SimdReal, const R: usize>(re: &mut [V; R], im: &mut [V; R], wr: &[V; R], wi: &[V; R], one: V) {\n");
    s.push_str("    // SAFETY: each arm only runs when R equals the array length it casts to.\n    unsafe {\n        match R {\n");
    for r in radices {
        let _ = writeln!(
            s,
            "            {r} => r{r}::t{r}(&mut *(re as *mut [V; R]).cast::<[V; {r}]>(), &mut *(im as *mut [V; R]).cast::<[V; {r}]>(), &*(wr as *const [V; R]).cast::<[V; {r}]>(), &*(wi as *const [V; R]).cast::<[V; {r}]>(), one),"
        );
    }
    s.push_str("            _ => unreachable!(),\n        }\n    }\n}\n");
    for (name, prefix, tw) in [("small_notw", "sn", false), ("small_tw", "st", true)] {
        let args = if tw { ", wr: &[V; R], wi: &[V; R]" } else { "" };
        let _ = writeln!(
            s,
            "/// Latency-oriented DFT without an opaque `one`.\n#[inline(always)]\npub(crate) unsafe fn {name}<V: SimdReal, const R: usize>(re: &mut [V; R], im: &mut [V; R]{args}) {{"
        );
        s.push_str(
            "// SAFETY: each arm casts only arrays whose lengths equal R.\nunsafe { match R {\n",
        );
        for r in radices {
            let extra = if tw {
                format!(
                    ", &*(wr as *const [V; R]).cast::<[V; {r}]>(), &*(wi as *const [V; R]).cast::<[V; {r}]>()"
                )
            } else {
                String::new()
            };
            let _ = writeln!(
                s,
                "{r} => r{r}::{prefix}{r}(&mut *(re as *mut [V; R]).cast::<[V; {r}]>(), &mut *(im as *mut [V; R]).cast::<[V; {r}]>(){extra}),"
            );
        }
        s.push_str("_ => unreachable!(),\n} }\n}\n");
    }
    s
}
