//! Focused Zen 4 choices, separate from the general cost model (ticket 18).
//! Incumbents: docs/benchmarks/2026-09-26-mini-ryzen-small-engine/.
//! Bounded latency experiments: ../2026-09-26-mini-ryzen-small-latency/.

use crate::engine::Shape;
use crate::isa::Isa;
use crate::planner::CandidateKernel;
use CandidateKernel::{GenericSmall as G, Stockham as S};
use Isa::{Avx2, Avx512, Avx512Ymm, Scalar, Sse2};

type Choice = (CandidateKernel, Isa, usize);

pub(super) fn preferred(n: usize, isa: Isa, f64_: bool) -> Option<(CandidateKernel, Shape)> {
    // Interleaved leaves, AVX-512VL's 32 registers first where the rows need
    // them. f64 N=64-256 need zmm rows (the AVX-512 tier); f32 N=128 gains
    // from them.
    let tiers: &[Isa] = match (f64_, n, isa) {
        (true, 64 | 128 | 256, Avx512) => &[Avx512],
        (false, 128, Avx512) => &[Avx512, Avx512Ymm, Avx2],
        (true, 32, Avx512Ymm | Avx512) | (false, 64 | 128 | 256, Avx512Ymm | Avx512) => {
            &[Avx512Ymm, Avx2]
        }
        (_, 2 | 4 | 8 | 16 | 32, Avx2 | Avx512Ymm | Avx512) | (false, 64 | 128 | 256, Avx2) => {
            &[Avx2]
        }
        _ => &[],
    };
    let compiled = crate::engine::small::interleaved_shapes(n, isa, f64_);
    tiers
        .iter()
        .map(|&isa| Shape {
            isa,
            lanes: crate::engine::small::interleaved_lanes(n, isa, f64_),
        })
        .find(|shape| compiled.contains(shape))
        .map(|shape| (CandidateKernel::InterleavedSmall, shape))
        .or_else(|| incumbent(n, isa, f64_))
}

/// Preserve the current-Small baseline fallback, including inside Measure's
/// first eight. This table is not generated by the latency analysis script.
pub(super) fn incumbent(n: usize, isa: Isa, f64_: bool) -> Option<(CandidateKernel, Shape)> {
    let choices: [Choice; 5] = match (f64_, n) {
        (false, 2 | 4) | (true, 2 | 3 | 6 | 9) => [(G, Scalar, 1); 5],
        (false, 3 | 5 | 6 | 7 | 8 | 9 | 10 | 11 | 13 | 15)
        | (true, 4 | 5 | 7 | 8 | 11 | 12 | 13 | 15) => [
            (G, Scalar, 1),
            (G, Scalar, 1),
            (G, Avx2, 1),
            (G, Avx2, 1),
            (G, Avx2, 1),
        ],
        (false, 12) => [
            (G, Scalar, 1),
            (G, Sse2, 4),
            (G, Avx2, 1),
            (G, Avx2, 1),
            (G, Avx2, 1),
        ],
        (true, 10) => [
            (G, Scalar, 1),
            (G, Scalar, 1),
            (G, Scalar, 1),
            (G, Avx512Ymm, 1),
            (G, Avx512Ymm, 1),
        ],
        (false, 14) | (true, 14) => [
            (G, Scalar, 1),
            (G, Scalar, 1),
            (G, Avx2, 1),
            (G, Avx512Ymm, 1),
            (G, Avx512Ymm, 1),
        ],
        (false, 16) => [
            (G, Scalar, 1),
            (G, Sse2, 4),
            (G, Sse2, 4),
            (G, Sse2, 4),
            (G, Sse2, 4),
        ],
        (false, 24 | 40 | 48 | 56) => [
            (S, Scalar, 1),
            (S, Sse2, 4),
            (G, Avx2, 8),
            (G, Avx512Ymm, 8),
            (G, Avx512Ymm, 8),
        ],
        (false, 32 | 64) => [
            (S, Scalar, 1),
            (S, Sse2, 4),
            (G, Avx2, 8),
            (S, Avx512Ymm, 8),
            (S, Avx512Ymm, 8),
        ],
        (false, 128 | 256) => [
            (S, Scalar, 1),
            (S, Sse2, 4),
            (S, Avx2, 8),
            (S, Avx512Ymm, 8),
            (S, Avx512Ymm, 8),
        ],
        (true, 16) => [
            (G, Scalar, 1),
            (G, Scalar, 1),
            (G, Avx2, 4),
            (G, Avx512Ymm, 4),
            (G, Avx512Ymm, 4),
        ],
        (true, 24) => [
            (S, Scalar, 1),
            (S, Sse2, 2),
            (S, Sse2, 2),
            (S, Sse2, 2),
            (G, Avx512, 8),
        ],
        (true, 32 | 40 | 48 | 56) => [
            (S, Scalar, 1),
            (S, Sse2, 2),
            (S, Avx2, 4),
            (S, Avx512Ymm, 4),
            (G, Avx512, 8),
        ],
        (true, 64) => [
            (S, Scalar, 1),
            (S, Sse2, 2),
            (S, Avx2, 4),
            (S, Avx512Ymm, 4),
            (S, Avx512, 8),
        ],
        (true, 128 | 256) => [
            (S, Scalar, 1),
            (S, Sse2, 2),
            (S, Avx2, 4),
            (S, Avx512Ymm, 4),
            (S, Avx512Ymm, 4),
        ],
        _ => return None,
    };
    let index = match isa {
        Scalar => 0,
        Sse2 => 1,
        Avx2 => 2,
        Avx512Ymm => 3,
        Avx512 => 4,
    };
    let (kernel, isa, lanes) = choices[index];
    Some((kernel, Shape { isa, lanes }))
}
